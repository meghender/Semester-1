#include <iostream>
#include <fstream>
#include <vector>
#include <map>
#include <set>
#include <string>
#include <sstream>
#include <stdexcept>

// Coordinate representation for the grid
struct Coord {
    int x, y;
    bool operator==(const Coord& o) const { return x == o.x && y == o.y; }
    bool operator!=(const Coord& o) const { return !(*this == o); }
};

// Metro route specification with a start and end point
struct Route {
    int lineNum;
    Coord origin, destination;
};

// Configuration parameters read from the input file
struct Config {
    int gridWidth, gridHeight, routeCount, maxBends;
    int scenarioType, hotspotCount;
    std::vector<Route> routes;
    std::vector<Coord> hotspots;
};

// Namespace for Scenario A logic, which uses a variable-to-signature map.
namespace ScenarioA {
    // This map stores the variable-to-signature mapping from the .varmap file.
    std::map<int, std::vector<int>> lookupTable;
    
    // Constants for signature parsing, which must match the encoder's definitions.
    const int SYM_NORTH = 2, SYM_SOUTH = 3, SYM_WEST = 4, SYM_EAST = 5;
    
    /**
     * @brief Loads the variable map generated by the encoder for Scenario A.
     * This file links SAT variable IDs to their logical meaning (e.g., move direction at a coordinate).
     */
    void loadVariableMap(const std::string& problemName) {
        std::ifstream mapFile(problemName + ".varmap");
        if (!mapFile.is_open()) {
            throw std::runtime_error("Could not open .varmap file for Scenario A.");
        }
        int varCount;
        mapFile >> varCount;
        
        std::string line;
        std::getline(mapFile, line); // Consume the rest of the first line

        while (std::getline(mapFile, line)) {
            std::stringstream ss(line);
            int varId;
            ss >> varId;
            
            std::vector<int> signature;
            int val;
            while (ss >> val) {
                signature.push_back(val);
            }
            if (!signature.empty()) {
                lookupTable[varId] = signature;
            }
        }
        mapFile.close();
    }

    /**
     * @brief Reconstructs a metro path by looking up true variables in the SAT solution.
     * It follows the path from origin to destination one step at a time.
     */
    std::string reconstructPath(const Route& route, const std::set<int>& solution, int gridW, int gridH) {
        std::string moves = "";
        Coord position = route.origin;
        int safetyLimit = gridW * gridH * 2; // A generous limit to prevent infinite loops
        
        for (int step = 0; step < safetyLimit && position != route.destination; ++step) {
            bool foundMove = false;
            
            // Search the solution set for a variable indicating the next move from the current position
            for (const int& varId : solution) {
                if (lookupTable.count(varId)) {
                    const std::vector<int>& signature = lookupTable.at(varId);
                    // A move signature has 4 parts: {TYPE, lineNum, y, x}
                    if (signature.size() == 4 && signature[1] == route.lineNum && 
                        signature[2] == position.y && signature[3] == position.x) {
                        
                        char moveChar = ' ';
                        if (signature[0] == SYM_NORTH) {
                            moveChar = 'U'; position.y--;
                        } else if (signature[0] == SYM_SOUTH) {
                            moveChar = 'D'; position.y++;
                        } else if (signature[0] == SYM_WEST) {
                            moveChar = 'L'; position.x--;
                        } else if (signature[0] == SYM_EAST) {
                            moveChar = 'R'; position.x++;
                        }

                        if (moveChar != ' ') {
                            // <<< FIX 1: Added space between moves.
                            if (!moves.empty()) moves += " ";
                            moves += moveChar;
                            foundMove = true;
                            break;
                        }
                    }
                }
            }
            
            if (!foundMove) {
                return "_PATH_RECONSTRUCTION_FAILED_";
            }
        }
        
        return moves;
    }
}

// Namespace for Scenario B logic, which reconstructs paths from state-space variables.
namespace ScenarioB {
    // Directions: 0=N, 1=S, 2=E, 3=W, 4=START
    const int dx[] = {0, 0, 1, -1};
    const int dy[] = {-1, 1, 0, 0};
    const char dirSymbols[] = {'U', 'D', 'R', 'L'};
    const int reverseDir[] = {1, 0, 3, 2};
    
    /**
     * @brief Computes the SAT variable for a given state.
     * This function must be identical to the one in the encoder.
     */
    int computeStateVar(int route, int col, int row, int direction, int bends, 
                        int gridW, int gridH, int bendLimit) {
        return 1 + bends + direction * (bendLimit + 1) + 
               row * (bendLimit + 1) * 5 + 
               col * (bendLimit + 1) * 5 * gridH + 
               route * (bendLimit + 1) * 5 * gridH * gridW;
    }

    /**
     * @brief Reconstructs a path by simulating the transitions from the start state.
     * At each step, it checks which potential next state is true in the SAT solution.
     */
    std::string reconstructPath(const Route& route, const std::set<int>& solution, const Config& cfg) {
        std::string moves = "";
        Coord currentPos = route.origin;
        int bendsUsed = 0;
        int arrivalDir = 4; // Special "START" direction

        int safetyLimit = cfg.gridWidth * cfg.gridHeight * 2;
        for (int step = 0; step < safetyLimit && currentPos != route.destination; ++step) {
            bool foundMove = false;

            // Iterate through all 4 possible move directions (U, D, R, L)
            for (int moveDir = 0; moveDir < 4; ++moveDir) {
                int nextX = currentPos.x + dx[moveDir];
                int nextY = currentPos.y + dy[moveDir];

                // Check if the move is within grid bounds
                if (nextX < 0 || nextX >= cfg.gridWidth || nextY < 0 || nextY >= cfg.gridHeight) {
                    continue;
                }

                int nextBends = bendsUsed;
                // A bend occurs if we aren't at the start and the move isn't straight
                if (arrivalDir != 4 && moveDir != reverseDir[arrivalDir]) {
                    nextBends++;
                }

                if (nextBends > cfg.maxBends) {
                    continue; // This move would exceed the bend limit
                }

                // Calculate the SAT variable for the potential next state
                int nextStateVar = computeStateVar(route.lineNum, nextX, nextY, 
                                                   reverseDir[moveDir], nextBends,
                                                   cfg.gridWidth, cfg.gridHeight, cfg.maxBends);
                
                // If this next state is true in the solution, we take this path
                if (solution.count(nextStateVar)) {
                    // <<< FIX 1: Added space between moves.
                    if (!moves.empty()) moves += " ";
                    moves += dirSymbols[moveDir];
                    currentPos = {nextX, nextY};
                    bendsUsed = nextBends;
                    arrivalDir = reverseDir[moveDir];
                    foundMove = true;
                    break; // Move found, proceed to the next step
                }
            }

            if (!foundMove) {
                return "_PATH_RECONSTRUCTION_FAILED_";
            }
        }
        return moves;
    }
}

int main(int argc, char* argv[]) {
    if (argc != 2) {
        std::cerr << "Usage: ./decoder <problem_name>" << std::endl;
        return 1;
    }
    
    std::string problemName = argv[1];
    Config cfg;
    
    // Step 1: Read the city configuration file
    std::ifstream cityFile(problemName + ".city");
    if (!cityFile.is_open()) {
        std::cerr << "Error: Cannot open " << problemName << ".city" << std::endl;
        return 1;
    }
    cityFile >> cfg.scenarioType >> cfg.gridWidth >> cfg.gridHeight >> cfg.routeCount >> cfg.maxBends;
    if (cfg.scenarioType == 2) {
        cityFile >> cfg.hotspotCount;
    } else {
        cfg.hotspotCount = 0;
    }
    for (int i = 0; i < cfg.routeCount; ++i) {
        Route r;
        r.lineNum = i;
        cityFile >> r.origin.x >> r.origin.y >> r.destination.x >> r.destination.y;
        cfg.routes.push_back(r);
    }
    if (cfg.scenarioType == 2 && cfg.hotspotCount > 0) {
        for (int i = 0; i < cfg.hotspotCount; ++i) {
            Coord h;
            cityFile >> h.x >> h.y;
            cfg.hotspots.push_back(h);
        }
    }
    cityFile.close();

    // Step 2: Read the SAT solver's output
    std::ifstream satOutputFile(problemName + ".satoutput");
    if (!satOutputFile.is_open()) {
        std::cerr << "Error: Cannot open " << problemName << ".satoutput" << std::endl;
        return 1;
    }
    std::string result;
    satOutputFile >> result;
    
    std::ofstream metroMapFile(problemName + ".metromap");

    if (result == "UNSAT") {
        // If unsatisfiable, output a single 0
        metroMapFile << "0\n";
    } else if (result == "SAT") {
        std::set<int> solution;
        int var;
        while (satOutputFile >> var && var != 0) {
            if (var > 0) {
                solution.insert(var);
            }
        }
        
        // Step 3: Decode the solution based on the scenario type
        if (cfg.scenarioType == 1) {
            try {
                ScenarioA::loadVariableMap(problemName);
                for (const auto& route : cfg.routes) {
                    std::string path = ScenarioA::reconstructPath(route, solution, cfg.gridWidth, cfg.gridHeight);
                    // <<< FIX 2: Added space before trailing '0'.
                    metroMapFile << path << " 0\n";
                }
            } catch (const std::runtime_error& e) {
                std::cerr << "Error during Scenario A decoding: " << e.what() << std::endl;
                return 1;
            }
        } else { // Scenario 2
            for (const auto& route : cfg.routes) {
                std::string path = ScenarioB::reconstructPath(route, solution, cfg);
                // <<< FIX 2: Added space before trailing '0'.
                metroMapFile << path << " 0\n";
            }
        }
    } else {
        std::cerr << "Error: Invalid SAT output format. Expected 'SAT' or 'UNSAT'." << std::endl;
        metroMapFile << "0\n"; // Default to unsatisfiable on error
        return 1;
    }
    
    satOutputFile.close();
    metroMapFile.close();

    return 0;
}